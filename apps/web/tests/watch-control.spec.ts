import { chooseSelect } from "./select";
import { expect, test } from '@playwright/test';
const apiOrigin = `http://127.0.0.1:${process.env.MOLLYTIME_E2E_PORT || '8098'}`;

test('parent enables a fixed playlist; TV PIN authorizes, completes, and cannot restart its allowance', async ({ page }, testInfo) => {
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto('/manage/');
  await page.getByLabel('账号', { exact: true }).fill('parent@example.test');
  await page.getByLabel('密码', { exact: true }).fill('parent-e2e');
  await page.getByRole('button', { name: '登录', exact: true }).click();
  await expect(page.getByRole('heading', { name: '概览', exact: true })).toBeVisible();
  const auth = await (await page.request.post(`${apiOrigin}/api/auth/login`, { headers: { 'X-Molly-Client': 'tv-shell/2' }, data: { username: 'parent@example.test', password: 'parent-e2e' } })).json();
  const headers = { Authorization: `Bearer ${auth.accessToken}` };
  const session = await (await page.request.get('/api/manage/auth/session')).json();
  await page.request.patch(`/api/manage/devices/${auth.deviceId}`, { headers: { 'X-CSRF-Token': session.csrfToken }, data: { name: '观看安排测试电视' } });
  // This TV has never reported playback capabilities and is shown as switched off.
  await page.route('**/api/manage/watch-control', async route => {
    const data = await (await route.fetch()).json();
    await route.fulfill({ json: { ...data, devices: data.devices.map((device: { deviceId: string }) => device.deviceId === auth.deviceId ? { ...device, online: false } : device) } });
  });
  await page.getByRole('link', { name: '观看设置', exact: true }).click();
  await expect(page.getByRole('tab', { name: '观看管理', exact: true })).toHaveAttribute('aria-selected', 'true');
  const device = page.getByRole('region', { name: '观看安排测试电视观看安排' });
  // section has an accessible name but browsers expose it as a region.
  await expect(device).toBeVisible({ timeout: 10000 });
  await expect(device.getByRole('button', { name: '开启观看管理', exact: true })).toBeEnabled();
  await device.getByRole('button', { name: '开启观看管理', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: '观看安排测试电视 · 观看设置' });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await expect(dialog.locator('input[type="number"]')).toHaveCount(0);
  await page.screenshot({ path: testInfo.outputPath('watch-settings-dialog-desktop.png') });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: testInfo.outputPath('watch-settings-dialog-mobile.png') });
  expect(await dialog.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true);
  await chooseSelect(dialog.getByLabel('观看方式', { exact: true }), 'minutes');
  await chooseSelect(dialog.getByLabel('每次看多久', { exact: true }), 'custom');
  await dialog.getByLabel('自定义分钟', { exact: true }).fill('25');
  await expect(dialog.getByText('每次看 25 分钟，时间到暂停并保存进度。', { exact: true })).toBeVisible();
  await expect(dialog.getByRole('button', { name: '保存设置', exact: true })).toBeInViewport();
  await page.screenshot({ path: testInfo.outputPath('watch-settings-time-custom-mobile.png') });
  await chooseSelect(dialog.getByLabel('观看方式', { exact: true }), 'episodes');
  await page.setViewportSize({ width: 1440, height: 1000 });
  const pinField = dialog.getByLabel('设置四位数字家长密码');
  if (await pinField.count()) await pinField.fill('1234');
  else await page.request.put('/api/manage/watch-control/pin', { headers: { 'X-CSRF-Token': session.csrfToken }, data: { pin: '1234' } });
  await expect(dialog.getByLabel('开启观看管理', { exact: true })).toBeChecked();
  await chooseSelect(dialog.getByLabel('每次看几集', { exact: true }), '2');
  await dialog.getByRole('button', { name: '保存设置', exact: true }).click();
  await expect(device.getByRole('button', { name: '允许观看', exact: true })).toBeVisible();
  await expect(device.getByRole('status')).toHaveText('已保存 · 电视离线，开机后同步');
  await page.reload();
  await expect(device.getByRole('button', { name: '允许观看', exact: true })).toBeEnabled();
  await expect(device.getByRole('status')).toHaveText('已保存 · 电视离线，开机后同步');
  await expect(page.getByRole('group', { name: '播放控制', exact: true })).toHaveCount(0);
  await page.screenshot({ path: testInfo.outputPath('watch-control-parent.png'), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
  await page.screenshot({ path: testInfo.outputPath('watch-control-parent-mobile.png'), fullPage: true });
  await page.setViewportSize({ width: 1440, height: 1000 });
  const tv = await page.context().newPage();
  tv.on('pageerror', e => errors.push(e.message));
  await tv.addInitScript(binding => localStorage.setItem('mollytime.tv.binding.v1', JSON.stringify(binding)), auth);
  await tv.goto(`${apiOrigin}/tv/`);
  await expect(tv.getByText('看完啦，休息一下吧。', { exact: true })).toBeVisible();
  await tv.getByRole('button', { name: '家长允许观看', exact: true }).click();
  await tv.getByRole('button', { name: '允许观看', exact: true }).click();
  await tv.keyboard.type('0000'); await tv.keyboard.press('Enter');
  await expect(tv.getByRole('alert')).toHaveText('家长密码不正确');
  await tv.keyboard.type('1234'); await tv.keyboard.press('Enter');
  await expect(tv.getByText('请输入家长密码', { exact: true })).toHaveCount(0);
  await tv.keyboard.press('Escape');
  await testInfo.attach('tv-before-selection', { body: await tv.locator('body').innerText(), contentType: 'text/plain' });
  await tv.screenshot({ path: testInfo.outputPath('tv-before-selection.png') });
  await tv.locator('[data-focus$="-series"]').click();
  await tv.locator('[data-focus="folder-season"]').click();
  await tv.locator('[data-focus="episode-browser-episode"]').click();
  const video = tv.getByRole('dialog', { name: '视频播放', exact: true }).locator(':scope > video');
  await expect.poll(() => video.evaluate(v => (v as HTMLVideoElement).readyState)).toBeGreaterThanOrEqual(2);
  await video.evaluate(v => { (v as HTMLVideoElement).pause(); });
  let state = await (await page.request.get(`${apiOrigin}/api/watch-control`, { headers })).json();
  expect(state.round.playlist).toEqual(['browser-episode', 'browser-next']);
  const finish = async () => { await video.evaluate(v => { (v as HTMLVideoElement).currentTime = (v as HTMLVideoElement).duration - 0.1; void (v as HTMLVideoElement).play(); }); };
  await finish();
  await expect.poll(async () => (await (await page.request.get(`${apiOrigin}/api/watch-control`, { headers })).json()).round.cursor).toBe(1);
  await expect.poll(() => video.evaluate(v => (v as HTMLVideoElement).readyState)).toBeGreaterThanOrEqual(2);
  await finish();
  await expect(tv.getByRole('dialog', { name: '视频播放', exact: true })).toHaveCount(0, { timeout: 10000 });
  await tv.reload();
  await expect(tv.getByText('看完啦，休息一下吧。', { exact: true })).toBeVisible();
  expect((await page.request.post(`${apiOrigin}/api/playback/sessions`, { headers, data: { episodeId: 'browser-episode' } })).status()).toBe(403);
  await tv.screenshot({ path: testInfo.outputPath('watch-control-tv-resting.png') });
  expect(errors).toEqual([]);
  await tv.close();
});

test('time limit stops real playback, keeps progress after reload, and parent adds ten minutes', async ({ page }) => {
  const auth = await (await page.request.post(`${apiOrigin}/api/auth/login`, { headers: { 'X-Molly-Client': 'tv-shell/2' }, data: { username: 'parent@example.test', password: 'parent-e2e' } })).json();
  const headers = { Authorization: `Bearer ${auth.accessToken}` };
  await page.request.post(`${apiOrigin}/api/watch-control/sync`, { headers, data: {} });
  await page.request.post('/api/manage/auth/login', { data: { username: 'parent@example.test', password: 'parent-e2e' } });
  const parent = await (await page.request.get('/api/manage/auth/session')).json();
  const parentHeaders = { 'X-CSRF-Token': parent.csrfToken };
  await page.request.put('/api/manage/watch-control/pin', { headers: parentHeaders, data: { pin: '1234' } });
  let state = await (await page.request.get(`${apiOrigin}/api/watch-control`, { headers })).json();
  const command = async (action: string, extra = {}) => {
    state = await (await page.request.get(`${apiOrigin}/api/watch-control`, { headers })).json();
    const result = await page.request.post(`/api/manage/watch-control/${auth.deviceId}/commands`, { headers: parentHeaders, data: { requestId: crypto.randomUUID(), version: state.version, action, ...extra } });
    expect(result.ok()).toBe(true); state = await result.json();
  };
  await command('settings', { enabled: true, mode: 'minutes', amount: 1 }); await command('allow');
  await page.request.post(`${apiOrigin}/api/watch-control/sync`, { headers, data: { roundId: state.round.id, playedMs: 59000 } });
  await page.addInitScript(binding => localStorage.setItem('mollytime.tv.binding.v1', JSON.stringify(binding)), auth);
  await page.goto(`${apiOrigin}/tv/`);
  await page.locator('[data-focus$="-series"]').click();
  await page.locator('[data-focus="folder-season"]').click();
  await page.locator('[data-focus="episode-browser-episode"]').click();
  await expect(page.getByRole('dialog', { name: '视频播放', exact: true })).toBeVisible();
  await expect(page.getByRole('dialog', { name: '视频播放', exact: true })).toHaveCount(0, { timeout: 10000 });
  await expect.poll(async () => (await (await page.request.get(`${apiOrigin}/api/watch-control`, { headers })).json()).status).toBe('resting');
  const progress = await (await page.request.get(`${apiOrigin}/api/episodes/browser-episode/progress`, { headers })).json();
  expect(progress.positionMs).toBeGreaterThan(0); expect(progress.completed).toBe(false);
  await page.reload(); await expect(page.getByText('看完啦，休息一下吧。', { exact: true })).toBeVisible();
  await command('add');
  await expect.poll(async () => (await (await page.request.get(`${apiOrigin}/api/watch-control`, { headers })).json()).status).toBe('allowed');
  state = await (await page.request.get(`${apiOrigin}/api/watch-control`, { headers })).json();
  expect(state.round.remainingMs).toBeGreaterThan(599000);
});
