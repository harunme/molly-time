test('time limit stops real playback, keeps progress after reload, and parent adds ten minutes', async ({ page }) => {
  const auth = await (await page.request.post(`${apiOrigin}/api/auth/login`, { headers: { 'X-Molly-Client': 'tv-shell/2' }, data: { username: 'parent@example.test', password: 'parent-e2e' } })).json();
  const headers = { Authorization: `Bearer ${auth.accessToken}` };
  await page.request.post(`${apiOrigin}/api/watch-control/sync`, { headers, data: {} });
  await page.request.post('/api/manage/auth/login', { data: { username: 'parent@example.test', password: 'parent-e2e' } });
  const parent = await (await page.request.get('/api/manage/auth/session')).json();
  const parentHeaders = { 'X-CSRF-Token': parent.csrfToken };
  await page.request.put('/api/manage/watch-control/pin', { headers: parentHeaders, data: { pin: '1234' } });
  let state = await (await page.request.get(`${apiOrigin}/api/watch-control`, { headers })).json();
  const command = async (action: string, extra = {}) => {
    state = await (await page.request.get(`${apiOrigin}/api/watch-control`, { headers })).json();
    const result = await page.request.post(`/api/manage/watch-control/${auth.deviceId}/commands`, { headers: parentHeaders, data: { requestId: crypto.randomUUID(), version: state.version, action, ...extra } });
    expect(result.ok()).toBe(true); state = await result.json();
  };
  await command('settings', { enabled: true, mode: 'minutes', amount: 1 }); await command('allow');
  await page.request.post(`${apiOrigin}/api/watch-control/sync`, { headers, data: { roundId: state.round.id, playedMs: 59000 } });
  await page.addInitScript(binding => localStorage.setItem('mollytime.tv.binding.v1', JSON.stringify(binding)), auth);
  await page.goto(`${apiOrigin}/tv/`);
  await page.locator('[data-focus$="-series"]').click();
  await page.locator('[data-focus="folder-season"]').click();
  await page.locator('[data-focus="episode-browser-episode"]').click();
  await expect(page.getByRole('dialog', { name: '视频播放', exact: true })).toBeVisible();
  await expect(page.getByRole('dialog', { name: '视频播放', exact: true })).toHaveCount(0, { timeout: 10000 });
  await expect.poll(async () => (await (await page.request.get(`${apiOrigin}/api/watch-control`, { headers })).json()).status).toBe('resting');
  const progress = await (await page.request.get(`${apiOrigin}/api/episodes/browser-episode/progress`, { headers })).json();
  expect(progress.positionMs).toBeGreaterThan(0); expect(progress.completed).toBe(false);
  await page.reload(); await expect(page.getByText('看完啦，休息一下吧。', { exact: true })).toBeVisible();
  await command('add');
  await expect.poll(async () => (await (await page.request.get(`${apiOrigin}/api/watch-control`, { headers })).json()).status).toBe('allowed');
  state = await (await page.request.get(`${apiOrigin}/api/watch-control`, { headers })).json();
  expect(state.round.remainingMs).toBeGreaterThan(599000);
});

test('TV saves a persistent rule and reuses it without choosing again, including custom backend values', async ({ page }, testInfo) => {
  const auth = await (await page.request.post(`${apiOrigin}/api/auth/login`, { headers: { 'X-Molly-Client': 'tv-shell/2' }, data: { username: 'parent@example.test', password: 'parent-e2e' } })).json();
  const headers = { Authorization: `Bearer ${auth.accessToken}` };
  await page.request.post('/api/manage/auth/login', { data: { username: 'parent@example.test', password: 'parent-e2e' } });
  const parent = await (await page.request.get('/api/manage/auth/session')).json();
  const parentHeaders = { 'X-CSRF-Token': parent.csrfToken };
  await page.request.put('/api/manage/watch-control/pin', { headers: parentHeaders, data: { pin: '1234' } });
  await page.setViewportSize({ width: 1280, height: 720 });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.addInitScript(binding => localStorage.setItem('mollytime.tv.binding.v1', JSON.stringify(binding)), auth);
  await page.goto(`${apiOrigin}/tv/`);
  const read = async () => (await (await page.request.get(`${apiOrigin}/api/watch-control`, { headers })).json());
  const open = async () => {
    const restingStart = page.getByRole('button', { name: '开始观看', exact: true });
    await expect.poll(async () => await restingStart.count() + await page.getByRole('button', { name: '打开设置', exact: true }).count()).toBeGreaterThan(0);
    if (await restingStart.count()) await restingStart.click();
    else {
      await page.getByRole('button', { name: '打开设置', exact: true }).click();
      await page.locator('[data-focus="open-watch-control"]').click();
    }
  };
  for (const [mode, amount] of [['episodes', 1], ['episodes', 2], ['episodes', 3], ['minutes', 15], ['minutes', 30], ['minutes', 60]] as const) {
    const label = `${amount} ${mode === 'episodes' ? '集' : '分钟'}`;
    await open();
    if (await page.getByRole('button', { name: '观看设置', exact: true }).count()) await page.getByRole('button', { name: '观看设置', exact: true }).click();
    await expect(page.getByRole('group', { name: '观看数量' }).getByRole('button')).toHaveCount(6);
    const choice = page.getByRole('button', { name: label, exact: true });
    await expect(choice).toBeInViewport();
    await choice.focus(); await page.keyboard.press('Enter');
    await expect(choice).toHaveAttribute('aria-pressed', 'true');
    await page.getByRole('button', { name: '保存设置', exact: true }).click();
    const before = await read();
    await page.keyboard.type('123');
    await expect(page.getByLabel('已输入 3 位密码')).toBeVisible();
    expect((await read()).version).toBe(before.version);
    if (amount === 60) await page.screenshot({ path: testInfo.outputPath('watch-pin-tv-720p.png') });
    await page.keyboard.type('4');
    await expect(page.getByRole('button', { name: `开始观看 · ${label}`, exact: true })).toBeVisible();
    const saved = await read();
    expect(saved.mode).toBe(mode); expect(saved.amount).toBe(amount); expect(saved.status).toBe('resting');
    await expect(page.getByRole('group', { name: '观看数量' })).toHaveCount(0);
    await page.getByRole('button', { name: `开始观看 · ${label}`, exact: true }).click();
    await page.keyboard.type('1234');
    await expect(page.getByRole('dialog')).toHaveCount(0);
    const started = await read(); expect(started.round.amount).toBe(amount);
    await page.reload();
    expect((await read()).round.id).toBe(started.round.id);
    await page.getByRole('button', { name: '打开设置', exact: true }).click();
    await page.locator('[data-focus="open-watch-control"]').click();
    await page.getByRole('button', { name: mode === 'episodes' ? '加看 1 集' : '加看 10 分钟', exact: true }).click();
    await page.keyboard.type('1234');
    await expect(page.getByRole('dialog')).toHaveCount(0);
    expect((await read()).amount).toBe(amount);
    await page.getByRole('button', { name: '打开设置', exact: true }).click();
    await page.locator('[data-focus="open-watch-control"]').click();
    await page.getByRole('button', { name: '结束观看', exact: true }).click();
    await page.keyboard.type('1234');
    await expect(page.getByText('看完啦，休息一下吧。', { exact: true })).toBeVisible();
  }
  const current = await read();
  const result = await page.request.post(`/api/manage/watch-control/${auth.deviceId}/commands`, { headers: parentHeaders, data: { requestId: crypto.randomUUID(), version: current.version, action: 'settings', enabled: true, mode: 'minutes', amount: 25 } });
  expect(result.ok()).toBe(true);
  await page.reload();
  await expect(page.getByRole('heading', { name: '看完啦，休息一下吧。', exact: true })).toBeVisible();
  await open();
  await expect(page.getByRole('button', { name: '开始观看 · 25 分钟', exact: true })).toBeFocused();
  await page.screenshot({ path: testInfo.outputPath('watch-start-tv-720p.png') });
  await page.getByRole('button', { name: '开始观看 · 25 分钟', exact: true }).click();
  await page.keyboard.type('1234');
  await expect(page.getByRole('dialog')).toHaveCount(0);
  expect((await read()).round.amount).toBe(25);
});

